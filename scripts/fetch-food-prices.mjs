/**
 * Regenerates src/engine/foodPricesSnapshot.ts, the food price data bundled with the app for when
 * /api/food-prices cannot be reached. Same two SCB queries as the function.
 *
 *   npm run food:prices
 *
 * SCB publishes the KPI around the 15th of the following month, and food sales by group once a year.
 */

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { buildFoodPrices } from '../api/food-prices.ts';

const prices = await buildFoodPrices();
const months = Object.keys(prices.index['01.1']).sort();
const body = `// Generated by scripts/fetch-food-prices.mjs on ${prices.fetchedAt.slice(0, 10)}. Do not edit.
import type { FoodPrices } from './foodPrices';

/** SCB KPI (2020 = 100) by COICOP group, ${months[0]} to ${months[months.length - 1]}, and ${prices.sales.year} grocery sales in MSEK. */
export const BUNDLED_FOOD_PRICES: FoodPrices = ${JSON.stringify({ ...prices, source: 'bundled' }, null, 2)};
`;

const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'engine', 'foodPricesSnapshot.ts');
await writeFile(target, body);
console.log(`Wrote ${path.relative(process.cwd(), target)}: ${months.length} months to ${months[months.length - 1]}, sales ${prices.sales.year}.`);
