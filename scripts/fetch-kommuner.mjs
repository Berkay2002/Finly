/**
 * Regenerates src/engine/tax/kommuner-<year>.ts from SCB's open data.
 *
 *   npm run tax:kommuner -- 2027
 *
 * SCB publishes the coming year's rates in mid-December (table OE0101, "Kommunalskatter").
 * After running, register the file in src/engine/tax/kommuner.ts and add the year's
 * parameters to src/engine/tax/years.ts.
 */

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const API = 'https://api.scb.se/OV0104/v1/doris/sv/ssd/START/OE/OE0101/Kommunalskatter2000';
const year = process.argv[2] ?? String(new Date().getFullYear() + 1);
if (!/^\d{4}$/.test(year)) {
  console.error('Usage: node scripts/fetch-kommuner.mjs <year>');
  process.exit(1);
}

const meta = await (await fetch(API)).json();
const region = meta.variables.find((v) => v.code === 'Region');
const names = Object.fromEntries(region.values.map((code, i) => [code, region.valueTexts[i]]));
const years = meta.variables.find((v) => v.code === 'Tid').values;
if (!years.includes(year)) {
  console.error(`SCB has no data for ${year} yet. Available: ${years.slice(-3).join(', ')}`);
  process.exit(1);
}

const res = await fetch(API, {
  method: 'POST',
  headers: { 'Content-Type': 'application/json' },
  body: JSON.stringify({
    query: [
      { code: 'Region', selection: { filter: 'all', values: ['*'] } },
      { code: 'ContentsCode', selection: { filter: 'item', values: ['OE0101D1'] } },
      { code: 'Tid', selection: { filter: 'item', values: [year] } },
    ],
    response: { format: 'json' },
  }),
});
const text = (await res.text()).replace(/^﻿/, '');
const data = JSON.parse(text);
const updated = data.metadata?.[0]?.updated?.slice(0, 10) ?? 'unknown';

const rates = Object.fromEntries(data.data.map((r) => [r.key[0], Number(r.values[0])]));
const counties = Object.fromEntries(
  Object.entries(names)
    .filter(([code]) => code.length === 2 && code !== '00')
    .map(([code, name]) => [code, name.replace(/ län$/, '')]),
);
const kommuner = Object.keys(names)
  .filter((code) => code.length === 4 && Number.isFinite(rates[code]))
  .sort((a, b) => names[a].localeCompare(names[b], 'sv'))
  .map((code) => ({ code, name: names[code], county: counties[code.slice(0, 2)], rate: rates[code] }));

const q = (s) => `'${s.replace(/'/g, "\\'")}'`;
const out = `/**
 * Total municipal income tax rate (kommun + region) per Swedish kommun, income year ${year}.
 *
 * GENERATED by scripts/fetch-kommuner.mjs from SCB table OE0101 (contents code OE0101D1,
 * ${API}), SCB data dated ${updated}.
 * Regenerate with \`npm run tax:kommuner -- ${year}\`; do not edit by hand.
 *
 * Rates exclude begravningsavgift and kyrkoavgift; those are added in sweden.ts.
 */

import type { Kommun } from './kommuner';

export const KOMMUNER_${year}: Kommun[] = [
${kommuner.map((k) => `  { code: ${q(k.code)}, name: ${q(k.name)}, county: ${q(k.county)}, rate: ${k.rate.toFixed(2)} },`).join('\n')}
];

export const NATIONAL_AVERAGE_RATE_${year} = ${rates['00'].toFixed(2)};
`;

const target = path.resolve(path.dirname(fileURLToPath(import.meta.url)), `../src/engine/tax/kommuner-${year}.ts`);
await writeFile(target, out, 'utf8');
console.log(`Wrote ${kommuner.length} kommuner to ${target} (SCB data ${updated})`);
